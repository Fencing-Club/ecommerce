export const shippingCopy: Record<DocumentLanguage, ShippingCopy> = { en, de, "zh-CN": zh, ur }
export type ShippingCopyKey = keyof ShippingCopy

export function shippingMessage(
  language: DocumentLanguage,
  key: ShippingCopyKey,
  values: Record<string, number | string> = {}
) {
  const number = new Intl.NumberFormat(language, { maximumFractionDigits: 2 })
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, typeof value === "number" ? number.format(value) : value),
    shippingCopy[language][key]
  )
}
