// Generates snippets/ui-icon.liquid from the Lucide icons listed in scripts/icons.json, using the lucide-static
// package's SVGs. Add a name to the list and run `pnpm --filter @repo/fc-theme-base icons:build`.
//
// Each icon's shapes become one path, so an icon is two elements however many shapes it has. Shapes with their own
// paint (Lucide's small filled dots) stay separate. The .ui-icon rules in component-ui.css paint the path.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const lucideIcons = resolve(dirname(require.resolve('lucide-static/package.json')), 'icons');

export const iconNames = JSON.parse(readFileSync(resolve(themeRoot, 'scripts/icons.json'), 'utf8'));
export const snippetPath = resolve(themeRoot, 'snippets/ui-icon.liquid');

const number = /-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/gi;
const format = (value) => String(Number(value.toFixed(4)));

/**
 * Path data for one shape, starting with an absolute moveto so it can follow another shape's data. A path that opens
 * with a relative `m` takes that first point as absolute, and the pairs after it are relative linetos.
 */
function shapeData(tag, attributes) {
  const value = (name, fallback = 0) => (name in attributes ? Number(attributes[name]) : fallback);
  switch (tag) {
    case 'path': {
      const d = attributes.d.trim();
      if (d[0] === 'M') return d;
      if (d[0] !== 'm') throw new Error(`A path starts with ${d[0]}`);
      const next = d.slice(1).search(/[a-z]/i);
      const first = next === -1 ? d.slice(1) : d.slice(1, next + 1);
      const rest = next === -1 ? '' : d.slice(next + 1);
      const [x, y, ...pairs] = first.match(number);
      return `M${x} ${y}${pairs.length ? `l${pairs.join(' ')}` : ''}${rest}`;
    }
    case 'circle':
    case 'ellipse': {
      const cx = value('cx');
      const cy = value('cy');
      const rx = tag === 'circle' ? value('r') : value('rx');
      const ry = tag === 'circle' ? value('r') : value('ry');
      return `M${format(cx - rx)} ${format(cy)}a${format(rx)} ${format(ry)} 0 1 0 ${format(2 * rx)} 0a${format(rx)} ${format(ry)} 0 1 0 ${format(-2 * rx)} 0`;
    }
    case 'rect': {
      const x = value('x');
      const y = value('y');
      const width = value('width');
      const height = value('height');
      const rx = Math.min(value('rx', value('ry')), width / 2);
      const ry = Math.min(value('ry', value('rx')), height / 2);
      if (!rx || !ry) return `M${format(x)} ${format(y)}h${format(width)}v${format(height)}h${format(-width)}z`;
      const corner = (dx, dy) => `a${format(rx)} ${format(ry)} 0 0 1 ${format(dx)} ${format(dy)}`;
      return [
        `M${format(x + rx)} ${format(y)}h${format(width - 2 * rx)}`,
        `${corner(rx, ry)}v${format(height - 2 * ry)}`,
        `${corner(-rx, ry)}h${format(-(width - 2 * rx))}`,
        `${corner(-rx, -ry)}v${format(-(height - 2 * ry))}`,
        `${corner(rx, -ry)}z`,
      ].join('');
    }
    case 'line':
      return `M${attributes.x1} ${attributes.y1}L${attributes.x2} ${attributes.y2}`;
    case 'polyline':
    case 'polygon': {
      const [x, y, ...pairs] = attributes.points.match(number);
      return `M${x} ${y}L${pairs.join(' ')}${tag === 'polygon' ? 'z' : ''}`;
    }
    default:
      throw new Error(`Lucide shape ${tag} has no path conversion`);
  }
}

/** An icon's shapes as one path, plus any shape with its own paint, on one line. */
export function iconBody(name) {
  const svg = readFileSync(resolve(lucideIcons, `${name}.svg`), 'utf8');
  const body = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!body) throw new Error(`lucide-static has no icon named ${name}`);
  const data = [];
  const painted = [];
  for (const [element, tag, attributeText] of body.matchAll(/<(\w+)([^>]*?)\s*\/>/g)) {
    const attributes = Object.fromEntries([...attributeText.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
    if ('fill' in attributes || 'stroke' in attributes) painted.push(element.replace(/\s*\/>$/, '/>'));
    else data.push(shapeData(tag, attributes));
  }
  return `<path d="${data.join('')}"/>${painted.join('')}`;
}

export function buildIconSnippet(names = iconNames) {
  const sorted = [...names].sort();
  const cases = sorted.map((name) => `    {%- when '${name}' -%}\n      ${iconBody(name)}`).join('\n');
  return `{%- comment -%}
  Generated by scripts/build-icons.mjs from lucide-static. Don't edit it by hand: add the icon's Lucide name to
  scripts/icons.json and run \`pnpm --filter @repo/fc-theme-base icons:build\`.

  Renders a decorative Lucide icon. Give the control around it the accessible name. The .ui-icon rules in
  component-ui.css paint it.

  Accepts:
  - icon: {String} A Lucide icon name from scripts/icons.json (required)
  - size: {Number} Width and height in pixels. Default: 16

  Usage:
  {% render 'ui-icon', icon: 'truck', size: 20 %}
{%- endcomment -%}
{%- assign size = size | default: 16 -%}
<svg class="ui-icon ui-icon--{{ icon }}" width="{{ size }}" height="{{ size }}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">
  {%- case icon -%}
${cases}
  {%- endcase -%}
</svg>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(snippetPath, buildIconSnippet());
  process.stdout.write(`Wrote ${iconNames.length} icons to snippets/ui-icon.liquid\n`);
}
